// The fixed schemes, used without dynamic colour: Material's tonal-spot scheme of each seed.
enum class Seed(
    val light: ColorScheme,
    val dark: ColorScheme,
) {
    Teal(tealLight, tealDark),
    Amber(amberLight, amberDark),
    ;

    fun scheme(dark: Boolean): ColorScheme = if (dark) this.dark else light
}

